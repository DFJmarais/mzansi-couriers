CREATE TABLE IF NOT EXISTS `relay_exception_events` (
  `id` int AUTO_INCREMENT NOT NULL,
  `deliveryId` int NOT NULL,
  `relayLegId` int,
  `reportedByUserId` int NOT NULL,
  `currentCustodianId` int,
  `type` enum('courier_delayed','receiving_courier_delayed','handoff_failed','address_clarification','recipient_unavailable','connectivity_concern','custody_review') NOT NULL,
  `status` enum('open','recovery_requested','resolved','cancelled') NOT NULL DEFAULT 'open',
  `recoveryAction` enum('wait_and_retry','safe_hold','request_replacement','operations_review'),
  `reason` varchar(500) NOT NULL,
  `note` text,
  `latitude` decimal(10,7),
  `longitude` decimal(11,7),
  `evidencePhotoUrl` text,
  `evidencePhotoKey` varchar(500),
  `customerNotifiedAt` timestamp NULL,
  `resolvedByUserId` int,
  `resolutionNote` text,
  `resolvedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  CONSTRAINT `relay_exception_events_deliveryId_deliveries_id_fk` FOREIGN KEY (`deliveryId`) REFERENCES `deliveries`(`id`),
  CONSTRAINT `relay_exception_events_relayLegId_delivery_relay_legs_id_fk` FOREIGN KEY (`relayLegId`) REFERENCES `delivery_relay_legs`(`id`),
  CONSTRAINT `relay_exception_events_reportedByUserId_users_id_fk` FOREIGN KEY (`reportedByUserId`) REFERENCES `users`(`id`),
  CONSTRAINT `relay_exception_events_currentCustodianId_users_id_fk` FOREIGN KEY (`currentCustodianId`) REFERENCES `users`(`id`),
  CONSTRAINT `relay_exception_events_resolvedByUserId_users_id_fk` FOREIGN KEY (`resolvedByUserId`) REFERENCES `users`(`id`)
);
