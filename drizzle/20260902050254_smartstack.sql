CREATE TABLE IF NOT EXISTS `smart_stack_recommendations` (
  `id` int AUTO_INCREMENT NOT NULL,
  `courierId` int NOT NULL,
  `status` enum('recommended','accepted','declined','expired','replaced') NOT NULL DEFAULT 'recommended',
  `stackScore` decimal(7,2) NOT NULL,
  `totalDistanceKm` decimal(10,2) NOT NULL,
  `totalTimeMinutes` int NOT NULL,
  `grossEarnings` decimal(12,2) NOT NULL,
  `platformFee` decimal(12,2) NOT NULL,
  `estimatedFuel` decimal(12,2) NOT NULL,
  `estimatedCourierNet` decimal(12,2) NOT NULL,
  `capacityUsedUnits` int NOT NULL,
  `capacityUnits` int NOT NULL,
  `deadlineRisk` enum('low','medium','high','critical') NOT NULL,
  `emptyKilometres` decimal(10,2) NOT NULL DEFAULT '0.00',
  `routeStops` json NOT NULL,
  `selectionReason` text,
  `expiresAt` timestamp NULL,
  `respondedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `smart_stack_recommendations_courier_status_idx` (`courierId`,`status`),
  CONSTRAINT `smart_stack_recommendations_courierId_users_id_fk` FOREIGN KEY (`courierId`) REFERENCES `users`(`id`)
);

CREATE TABLE IF NOT EXISTS `smart_addon_opportunities` (
  `id` int AUTO_INCREMENT NOT NULL,
  `recommendationId` int,
  `courierId` int NOT NULL,
  `deliveryId` int NOT NULL,
  `status` enum('offered','accepted','declined','expired','cancelled') NOT NULL DEFAULT 'offered',
  `additionalDistanceKm` decimal(10,2) NOT NULL,
  `additionalTimeMinutes` int NOT NULL,
  `additionalPayout` decimal(12,2) NOT NULL,
  `deadlineRisk` enum('low','medium','high','critical') NOT NULL,
  `score` decimal(7,2) NOT NULL,
  `reason` text NOT NULL,
  `expiresAt` timestamp NULL,
  `respondedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `smart_addon_opportunities_courier_status_idx` (`courierId`,`status`),
  KEY `smart_addon_opportunities_delivery_idx` (`deliveryId`),
  CONSTRAINT `smart_addon_opportunities_courierId_users_id_fk` FOREIGN KEY (`courierId`) REFERENCES `users`(`id`),
  CONSTRAINT `smart_addon_opportunities_deliveryId_deliveries_id_fk` FOREIGN KEY (`deliveryId`) REFERENCES `deliveries`(`id`)
);

CREATE TABLE IF NOT EXISTS `smart_match_audits` (
  `id` int AUTO_INCREMENT NOT NULL,
  `courierId` int NOT NULL,
  `deliveryId` int NOT NULL,
  `recommendationId` int,
  `matchScore` decimal(7,2) NOT NULL,
  `routeCompatibilityScore` decimal(7,2) NOT NULL,
  `deadlineRisk` enum('low','medium','high','critical') NOT NULL,
  `decision` enum('recommended','accepted','declined','rejected','completed','cancelled') NOT NULL DEFAULT 'recommended',
  `routeConsidered` json,
  `reason` text NOT NULL,
  `outcomeNote` text,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `smart_match_audits_courier_delivery_idx` (`courierId`,`deliveryId`),
  KEY `smart_match_audits_decision_idx` (`decision`),
  CONSTRAINT `smart_match_audits_courierId_users_id_fk` FOREIGN KEY (`courierId`) REFERENCES `users`(`id`),
  CONSTRAINT `smart_match_audits_deliveryId_deliveries_id_fk` FOREIGN KEY (`deliveryId`) REFERENCES `deliveries`(`id`)
);
