CREATE TABLE IF NOT EXISTS `vehicle_cost_profiles` (
  `id` int AUTO_INCREMENT NOT NULL,
  `courierId` int NOT NULL,
  `vehicleType` varchar(40) NOT NULL,
  `makeModel` varchar(120),
  `modelYear` int,
  `fuelType` varchar(30) NOT NULL DEFAULT 'petrol',
  `fuelPricePerLitre` decimal(8,2) NOT NULL,
  `fuelLitresPer100Km` decimal(6,2) NOT NULL,
  `driverCompensationPerKm` decimal(8,2) NOT NULL,
  `vehicleAllowancePerKm` decimal(8,2) NOT NULL,
  `routeOverheadPerKm` decimal(8,2) NOT NULL,
  `verificationStatus` enum('pending','verified','rejected') NOT NULL DEFAULT 'pending',
  `evidenceNote` text,
  `verifiedBy` int,
  `verifiedAt` timestamp,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `vehicle_cost_profiles_id` PRIMARY KEY(`id`)
);

CREATE TABLE IF NOT EXISTS `relay_settlement_allocations` (
  `id` int AUTO_INCREMENT NOT NULL,
  `settlementKey` varchar(160) NOT NULL,
  `deliveryId` int NOT NULL,
  `relayLegId` int,
  `courierId` int NOT NULL,
  `vehicleCostProfileId` int,
  `weekStart` date NOT NULL,
  `customerCharge` decimal(12,2) NOT NULL,
  `platformFee` decimal(12,2) NOT NULL,
  `courierPool` decimal(12,2) NOT NULL,
  `linehaulDistanceKm` decimal(10,2) NOT NULL,
  `deadheadKm` decimal(10,2) NOT NULL,
  `returnKm` decimal(10,2) NOT NULL,
  `totalDrivenKm` decimal(10,2) NOT NULL,
  `operatingCost` decimal(12,2) NOT NULL,
  `handoverFee` decimal(12,2) NOT NULL,
  `grossEarnings` decimal(12,2) NOT NULL,
  `estimatedNet` decimal(12,2) NOT NULL,
  `status` enum('calculated','approved','paid','void') NOT NULL DEFAULT 'calculated',
  `payoutId` int,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `relay_settlement_allocations_id` PRIMARY KEY(`id`),
  CONSTRAINT `relay_settlement_allocations_settlementKey_unique` UNIQUE(`settlementKey`)
);
